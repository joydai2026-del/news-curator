#!/usr/bin/env node
// Regenerate the committed edge fixtures. No dependencies: Node's standard
// library only, same as the test suite.
//
//   node edge/scripts/regenerate-fixtures.mjs
//
// This is the ONLY thing that writes edge/fixtures/. The test suite reads them
// unconditionally, so a missing fixture is ENOENT (red) and a drifted one is a
// byte-comparison failure (red). Neither self-heals. Run this only when you
// MEANT to change the emitted shape, and reconcile the change with
// curator/contracts/receipt.py in the same commit.
//
// CI runs `git diff --exit-code -- edge/fixtures` after the suite, so a fixture
// regenerated by accident cannot reach main green either.

import { renameSync, unlinkSync, writeFileSync } from 'node:fs';

import { buildSampleReceipt, SAMPLE_FIXTURE_PATH } from '../_helpers.js';

const serialized = `${JSON.stringify(buildSampleReceipt(), null, 2)}\n`;

// Write a sibling temp file and rename it into place. A crash or a full disk
// midway through a direct write leaves a TRUNCATED fixture, which is a fixture
// that no longer says what the contract is while still looking committed. The
// rename is atomic within the directory, so the file is either the old bytes or
// the new ones, never half of each.
const tmpPath = `${SAMPLE_FIXTURE_PATH}.tmp-${process.pid}`;
try {
  writeFileSync(tmpPath, serialized);
  renameSync(tmpPath, SAMPLE_FIXTURE_PATH);
} catch (err) {
  try {
    unlinkSync(tmpPath);
  } catch {
    // Nothing to clean up. The original write is the failure worth reporting.
  }
  throw err;
}
console.log(`wrote ${SAMPLE_FIXTURE_PATH} (${serialized.length} bytes)`);
