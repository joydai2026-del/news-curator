-- Session guards. The 28 generated ownership CHECK constraints below embed
-- regex escapes (\uXXXX / \UXXXXXXXX) inside PLAIN single-quoted literals,
-- which reach the regex engine as escapes only while
-- standard_conforming_strings is on (the Postgres default since 9.1). With
-- it off the same literal is parsed as an escape string and the leading NUL
-- escape is a string-literal error, so the migration would fail to apply.
-- The check text depends on this setting; do not remove the line.
--
-- ASSUMED RUNNER (round-6 should-fix): this guard protects the literals below
-- ONLY under a runner that sends statements one at a time (psql, and the
-- Supabase CLI's migration runner, which both split on `;`). Postgres's
-- simple Query protocol parses an ENTIRE multi-statement string into raw
-- parse trees, with string-literal escaping resolved at scan time, BEFORE
-- executing any statement in it; a runner that sends this whole file as one
-- string would parse all 28 literals before this SET takes effect, so the
-- guard would protect nothing in its own file under that runner. With the
-- setting off the literals fail LOUDLY (an invalid four-digit NUL escape)
-- rather than corrupting silently, so this is about the guard's honesty
-- under an unverified runner, not a corruption path.
set standard_conforming_strings = on;

-- Learning ledger: append-only behavioral history plus the durable records
-- that hang off it (evidence, artifacts, receipts). Modeled on the frozen
-- dataclasses in curator/contracts/{event,evidence,artifact,receipt,mirror,
-- tenant}.py. See docs/contracts/ledger-storage.md for the plain-English
-- summary of what this migration implements and what it deliberately does
-- not build yet.
--
-- Every table that stores a PRIVATE RECORD carries the same four ownership
-- columns, because the frozen dataclasses now inherit one shared Ownership
-- shape (curator/contracts/tenant.py):
--
--   tenant_id  text not null   the isolation boundary
--   actor_id   text not null   who wrote the row (no default: an empty
--                              actor_id used to be a column default, so an
--                              unattributed row was the default value)
--   actor_kind text not null   human | agent | system
--   user_id    text not null   the human the record is ABOUT
--
-- TWO-TIER SUBJECT ATTRIBUTION (2026-09-02). A record is SUBJECT-BOUND when a
-- "delete everything about me" request must be able to find it. All nine
-- tables below are subject-bound (behaviour, imports, artifacts, and the
-- receipts that prove their deletion), so user_id here is `not null` whatever
-- wrote the row: a system writer does not erase the human subject. The
-- `check (actor_kind = 'system' or user_id is not null)` form these tables
-- used to carry is gone; it let a normalizer-written row about one person
-- name nobody. Subjectless records (source checkpoints, plugin registry rows,
-- normalized public documents, pipeline intermediates) may carry a null
-- user_id and have no table here yet. The classification is frozen in
-- curator/contracts/__init__.py (SUBJECT_BOUND_RECORDS / SUBJECTLESS_RECORDS).
--
-- BLANK IS NOT NULL, AND NON-BLANK IS NOT CANONICAL. `not null`, `non-blank`
-- and `canonical` are three different rules, so every ownership column carries
-- all three clauses: equal to its own btrim, at least one non-space character,
-- and no invisible code point. Without the first, an empty actor_id (the exact
-- unattributed value this shape removed as a column default) and an empty
-- user_id were both legal and a deletion sweep filtering `user_id is null`
-- silently missed the blank rows. The old form was `btrim(x) <> ''`, and
-- btrim with no second argument strips SPACES ONLY: a live INSERT of a tab,
-- a newline, U+00A0 or U+3000 (one keystroke on a Chinese IME) was accepted by
-- the database while both Python validators rejected it. The invisible class
-- below is GENERATED by curator.ownership.ownership_id_sql_check from
-- INVISIBLE_ID_CODE_POINT_RANGES in curator/contracts/__init__.py; do not hand
-- edit it. A freeze test regenerates the text and fails on any drift.
--
-- FOURTH CLAUSE, `is nfc normalized` (2026-09-02). NFC and NFD spellings of
-- one visible id are two rows no reviewer can tell apart, so a per-person
-- delete keyed on the composed spelling misses the decomposed row. REQUIRES
-- PostgreSQL 13 or later on a UTF8 database; `IS NORMALIZED` is a core
-- predicate there and needs no extension. It is immutable, so it is legal
-- inside a CHECK. The Python half is curator.ownership.noncanonical_id_reason.
-- Unpaired surrogates are refused by the Python half only: a UTF8 database
-- cannot store one, so the write fails on encoding before any check runs.
--
-- KNOWN FAILURE MODE (round-6 should-fix, undiagnosed until now): Postgres
-- refuses a CHECK whose expression calls a non-IMMUTABLE function. If
-- `unicode_is_normalized` is not marked immutable on the target server, this
-- migration fails at the FIRST `create table` below, not at insert time. If a
-- live application of this file fails there, that is the diagnosis in one
-- line rather than a symptom to re-derive; it is not the astral escapes or
-- the widened invisible range, both of which are plain regex literals with no
-- such dependency.
--
-- Edited in place rather than superseded by a second migration: this file has
-- not been applied to any environment (grade B, the phase-4 slice records no
-- cloud mutation).
--
-- KNOWN OPEN, deferred with a corrected reason (2026-09-02): the four
-- `*_update_own` policies gate on tenant membership only, so any member may
-- `update ... set actor_id / actor_kind / user_id` after insert and rewrite the
-- attribution these columns exist to hold. The earlier stated blocker ("the
-- migration has an execution receipt") does not hold: that receipt covers a
-- scratch Postgres cluster, and the migration is presumed unapplied at grade C
-- because no live `schema_migrations` query has ever been run. A scratch
