-- Exact `=` is correct here, not an approximation: both sides are canonical
-- BY CONSTRAINT. `m.tenant_id` carries the generated ownership_id_sql_check
-- above, and every caller of this function passes a `tenant_id` column that
-- carries the same check (see the per-table CHECK constraints below), so
-- neither side can be padded, carry an invisible code point, or sit in NFD.
-- Two canonical spellings of one tenant are the same string, which is what
-- makes exact string comparison sufficient rather than merely convenient.
create or replace function public.is_tenant_member(check_tenant_id text)
returns boolean
language sql
stable
security invoker
set search_path = pg_catalog, public
as $$
  select exists (
    select 1
    from public.tenant_members m
    where m.tenant_id = check_tenant_id and m.auth_uid = auth.uid()
  )
$$;

revoke execute on function public.is_tenant_member(text) from public, anon;
grant execute on function public.is_tenant_member(text) to authenticated;

-- ---------------------------------------------------------------------
-- Append-only enforcement: shared trigger function. Attached below to
-- learning_events, correction_events, evidence_items, artifact_versions.
-- Blocks UPDATE and DELETE for every role, including service_role, since a
-- trigger fires regardless of RLS or grants. Retraction is a new row in
-- correction_events, never an edit to the row being retracted.
-- ---------------------------------------------------------------------

create or replace function public.reject_ledger_mutation()
returns trigger
language plpgsql
set search_path = pg_catalog
as $$
begin
  raise exception using
    errcode = '0A000',
    message = format(
      'append-only table %I: %s is not permitted; write a new row instead',
      TG_TABLE_NAME, TG_OP
    );
end;
$$;

revoke execute on function public.reject_ledger_mutation() from public, anon, authenticated;

