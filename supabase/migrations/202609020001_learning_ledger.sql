-- NAME COLLISION, resolved rather than papered over: this column holds an
-- AUTH PROVIDER SUBJECT (an auth.users uuid), while the contract's `user_id`
-- (curator/contracts/tenant.py: Ownership) is a stable, provider-neutral text
-- id that appears on every private record below. Two different things cannot
-- share one column name in the same schema, so the auth subject is `auth_uid`
-- here and `user_id` means the contract's value everywhere else.
--
-- Mapping one onto the other is the identity adapter's job (SC-32) and is
-- DEFERRED: no table below joins auth_uid to user_id yet, and nothing reads
-- user_id for authorization. Row isolation is keyed on tenant membership
-- alone, exactly as before.
create table public.tenant_members (
  tenant_id text not null,
  auth_uid uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default statement_timestamp(),
  primary key (tenant_id, auth_uid),
  -- Round 6: this was the ONE table in this migration carrying zero of the
  -- three canonical clauses the 27 (now 28) other ownership columns all
  -- carry. A membership row inserted with a stray trailing space would never
  -- equal the canonical tenant_id every owned table now REQUIRES, and
  -- is_tenant_member (below) compares by exact string equality, so that
  -- member would be silently denied select/insert on every table. Generated
  -- by the same curator.ownership.ownership_id_sql_check('tenant_id') as the
  -- rest; test_the_migration_ownership_checks_are_derived_from_the_frozen_set
  -- now asserts 28.
  check (tenant_id = btrim(tenant_id) and tenant_id ~ '[^[:space:]]' and tenant_id !~ '[\u0000-\u0020\u007F-\u00A0\u00AD\u0600-\u0605\u061C\u06DD\u070F\u0890-\u0891\u08E2\u1680\u180E\u2000-\u200F\u2028-\u202F\u205F-\u2064\u2066-\u206F\u3000\uFEFF\uFFF9-\uFFFB\U000110BD\U000110CD\U00013430-\U00013438\U0001BCA0-\U0001BCA3\U0001D173-\U0001D17A\U000E0001\U000E0020-\U000E007F]' and tenant_id is nfc normalized)
